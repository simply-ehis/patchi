"""`p why --out` / `p impact --out` — markdown reports written for PRs/docs.

The contract: the file is valid pastable markdown (fenced mermaid for the
mermaid path), stdout never duplicates the report, and every failure mode
honestly reports on stderr with a non-zero exit instead of silently writing
a wrong or empty file.
"""

import pytest

from patchi.cli.commands.reason_cmd import run_impact, run_why


@pytest.fixture()
def graph_root(tmp_path, monkeypatch):
    """A project root whose cached brain memory holds a small import graph:

        caller_a.py  -> core.py
        caller_b.py  -> core.py
        core.py      -> helper.py, other.py
    """
    import patchi.core.memory as mem

    data = {
        "import_graph": {
            "nodes": ["caller_a.py", "caller_b.py", "core.py", "helper.py", "other.py"],
            "edges": {
                "caller_a.py": ["core.py"],
                "caller_b.py": ["core.py"],
                "core.py": ["helper.py", "other.py"],
            },
        }
    }
    monkeypatch.setattr(mem, "get_brain", lambda root=None, *a, **k: data)
    return tmp_path


@pytest.fixture()
def no_brain(tmp_path, monkeypatch):
    """A project root with NO layered brain (engine.why returns an error)."""
    import patchi.core.memory as mem

    monkeypatch.setattr(mem, "get_brain", lambda root=None, *a, **k: {})
    return tmp_path


# ── p why --out ──────────────────────────────────────────────────────────────


def test_why_mermaid_out_writes_fenced_report(graph_root):
    out = graph_root / "report.md"
    run_why("core.py", root=graph_root, mermaid=True, out=out)
    text = out.read_text(encoding="utf-8")
    assert text.count("```mermaid") == 2  # dependents walk + call-flow walk
    assert "caller_a" in text or "caller_b" in text  # dependents walk names an importer
    assert "helper" in text or "other" in text  # call-flow walk names an import


def test_why_mermaid_out_does_not_duplicate_on_stdout(graph_root, capsys):
    out = graph_root / "report.md"
    run_why("core.py", root=graph_root, mermaid=True, out=out)
    stdout = capsys.readouterr().out
    assert "```mermaid" not in stdout  # diagram only in the file, not also stdout
    assert out.name in stdout  # but stdout says where the report went


def test_why_out_without_brain_fails_honestly(no_brain):
    out = no_brain / "report.md"
    with pytest.raises(SystemExit) as exc:
        run_why("core.py", root=no_brain, out=out)
    assert exc.value.code == 1
    assert not out.exists()  # no report on failure — silent partial output is worse


def test_why_mermaid_out_without_graph_fails_honestly(no_brain):
    out = no_brain / "report.md"
    with pytest.raises(SystemExit) as exc:
        run_why("core.py", root=no_brain, mermaid=True, out=out)
    assert exc.value.code == 1
    assert not out.exists()


def test_why_out_creates_missing_parent_dirs(graph_root):
    out = graph_root / "docs" / "deep" / "report.md"
    run_why("core.py", root=graph_root, mermaid=True, out=out)
    assert out.exists()


