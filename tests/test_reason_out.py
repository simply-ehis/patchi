@pytest.fixture()
def impact_root(graph_root, monkeypatch):
    """graph_root + the layered brain fields impact_analysis needs."""
    import patchi.core.memory as mem
    from patchi.cli.commands import reason_cmd
    from patchi.core.brain.reasoning import ImpactAnalysis

    analysis = ImpactAnalysis(
        changed_files=["core.py"],
        affected_layers=["core-layer"],
        impacted_layers=["api-layer", "web-layer"],
        summary="1 file(s) changed; 1 layer(s) directly affected; 2 downstream layer(s).",
    )

    class _FakeEngine:
        def __init__(self, root):
            pass

        def impact_analysis(self, files):
            return analysis

    monkeypatch.setattr(reason_cmd, "ReasoningEngine", _FakeEngine)
    monkeypatch.setattr(
        mem,
        "get_brain",
        lambda root=None, *a, **k: {"import_graph": {"nodes": ["core.py"], "edges": {}}},
    )
    return graph_root


def test_impact_out_writes_markdown_report(impact_root):
    out = impact_root / "impact.md"
    run_impact(["core.py"], root=impact_root, out=out)
    text = out.read_text(encoding="utf-8")
    assert "# Impact analysis" in text
    assert "## Directly affected layers" in text
    assert "`core-layer`" in text
    assert "## Blast radius (downstream dependents)" in text
    assert "`web-layer`" in text
    assert "Generated by" in text  # provenance stamp


def test_impact_out_does_not_duplicate_on_stdout(impact_root, capsys):
    out = impact_root / "impact.md"
    run_impact(["core.py"], root=impact_root, out=out)
    stdout = capsys.readouterr().out
    assert "Impact analysis" not in stdout
    assert out.name in stdout


def test_impact_out_without_files_fails_honestly(impact_root):
    out = impact_root / "impact.md"
    with pytest.raises(SystemExit) as exc:
        run_impact([], root=impact_root, out=out)
    assert exc.value.code == 1
    assert not out.exists()


def test_impact_all_out_writes_blast_table(graph_root):
    """--all --out renders the full blast-radius map as a markdown table.

    Semantics (same as the human table): Direct = immediate dependents;
    Total = transitive dependents closure (files affected by changing this
    one, excluding the file itself). For core.py: 2 direct callers, total 2.
    """
    from patchi.cli.commands import reason_cmd

    graph = reason_cmd._cached_graph(graph_root)
    out = graph_root / "blast.md"
    reason_cmd._write_out(out, reason_cmd._radii_markdown(reason_cmd._blast_radii(graph)))
    text = out.read_text(encoding="utf-8")
    assert "# Blast radius map" in text
    assert "| File | Direct | Total | Risk |" in text
    assert "| `core.py` | 2 | 2 | MED |" in text
    assert "| `helper.py` | 1 | 3 | MED |" in text  # core + both callers transitively
    assert "| `caller_a.py` | — | — | LOW |" in text  # nothing depends on it


def test_impact_out_and_json_are_rejected(impact_root):
    out = impact_root / "impact.json.md"
    with pytest.raises(SystemExit) as exc:
        run_impact(["core.py"], json_output=True, root=impact_root, out=out)
    assert exc.value.code == 2
    assert not out.exists()


