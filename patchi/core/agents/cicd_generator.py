"""CICDGeneratorAgent — generates CI/CD configs and pre-commit hooks.

Covers §10.1.1-4:
- Pre-commit hook config (.pre-commit-config.yaml)
- GitHub Actions workflow
- GitLab CI template
- Branch protection gate suggestions
"""

from __future__ import annotations

from .base import (
    AgentGroup,
    AgentInput,
    AgentResult,
    AgentStatus,
    BaseAgent,
    Severity,
    make_finding,
    register,
)

_PRE_COMMIT_CONFIG = """# Auto-generated by Patchi — pre-commit hooks for instant feedback
repos:
  - repo: https://github.com/pre-commit/pre-commit-hooks
    rev: v4.6.0
    hooks:
      - id: trailing-whitespace
      - id: end-of-file-fixer
      - id: check-yaml
      - id: check-json
      - id: check-added-large-files
      - id: detect-private-key

  - repo: local
    hooks:
      - id: patchi-scan
        name: Patchi scan
        entry: patchi scan --staged
        language: system
        pass_filenames: false
"""

_GITHUB_ACTIONS_WORKFLOW = """# Auto-generated by Patchi — CI workflow
name: Patchi CI
on:
  push:
    branches: [main, develop]
  pull_request:
    branches: [main]

jobs:
  analyze:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Run Patchi
        uses: anomalyco/patchi-action@v1
        with:
          github_token: ${{ secrets.GITHUB_TOKEN }}

      - name: Upload SARIF
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: .patchi/output.sarif
"""

_GITLAB_CI_TEMPLATE = """# Auto-generated by Patchi — GitLab CI template
stages:
  - analyze

patchi-scan:
  stage: analyze
  image: python:3.11-slim
  before_script:
    - pip install patchi
  script:
    - patchi scan
  artifacts:
    reports:
      code_quality: .patchi/output.sarif
"""


@register
class CICDGeneratorAgent(BaseAgent):
    """Generates CI/CD configs: pre-commit hooks, GitHub Actions, GitLab CI, branch protection."""

    group = AgentGroup.GUARD
    name = "CICDGeneratorAgent"
    description = "Generate .pre-commit-config.yaml, GitHub Actions, GitLab CI, and branch protection gates"

    def _run(self, inp: AgentInput, result: AgentResult) -> None:
        existing_precommit = inp.root / ".pre-commit-config.yaml"
        existing_github = inp.root / ".github" / "workflows" / "patchi-ci.yml"
        existing_gitlab = inp.root / ".gitlab-ci.yml"

        result.data["generated"] = []

        if not existing_precommit.exists():
            result.data["generated"].append(".pre-commit-config.yaml")
            result.findings.append(
                make_finding(
                    self.name,
                    "precommit_config",
                    Severity.INFO,
                    ".pre-commit-config.yaml",
                    "Generate pre-commit hook config for instant feedback",
                    detail=_PRE_COMMIT_CONFIG[:200],
                    suggestion="Run `patchi fix` to write this file",
                )
            )

        if not existing_github.exists():
            result.data["generated"].append(".github/workflows/patchi-ci.yml")
            result.findings.append(
                make_finding(
                    self.name,
                    "github_actions_workflow",
                    Severity.INFO,
                    ".github/workflows/patchi-ci.yml",
                    "Generate GitHub Actions workflow for CI",
                    detail=_GITHUB_ACTIONS_WORKFLOW[:200],
                    suggestion="Run `patchi fix` to write this file",
                )
            )

        if not existing_gitlab.exists():
            result.data["generated"].append(".gitlab-ci.yml")
            result.findings.append(
                make_finding(
                    self.name,
                    "gitlab_ci_template",
                    Severity.INFO,
                    ".gitlab-ci.yml",
                    "Generate GitLab CI template for CI",
                    detail=_GITLAB_CI_TEMPLATE[:200],
                    suggestion="Run `patchi fix` to write this file",
                )
            )

        # Branch protection gates check
        has_branch_protection = False
        for conf in ["CODEOWNERS", ".github/CODEOWNERS", "CODEOWNERS.txt"]:
            if (inp.root / conf).exists():
                has_branch_protection = True
                break

        if not has_branch_protection:
            result.findings.append(
                make_finding(
                    self.name,
                    "branch_protection",
                    Severity.MEDIUM,
                    "",
                    "No branch protection or CODEOWNERS detected",
                    detail="Set up branch protection rules requiring Patchi to pass before merge",
                    suggestion="Configure branch protection in GitHub/GitLab settings",
                )
            )

        result.data["templates"] = {
            "precommit": _PRE_COMMIT_CONFIG,
            "github_actions": _GITHUB_ACTIONS_WORKFLOW,
            "gitlab_ci": _GITLAB_CI_TEMPLATE,
        }

        result.files_scanned = 3
        if result.status == AgentStatus.RUNNING:
            result.status = AgentStatus.DONE
